public class Ativ6 {
    public static void main(String[] args) {
        System.out.println("--- Números um abaixo do outro ---");
        for (int i = 1; i <= 20; i++) {
            System.out.println(i);
        }

        System.out.println("\n--- Números um ao lado do outro ---");
        for (int i = 1; i <= 20; i++) {
            System.out.print(i + " ");
        }
        System.out.println();
    }
}
